#!/usr/bin/env bash
# Creates a SIP trunk from a provider template, like the 3CX "Add SIP Trunk" wizard.
# Asks only for the fields the provider needs; the password is never echoed or logged.
#
# Usage: ./add-trunk.sh <provider> <trunk-name> [inbound-extension]
#   provider:          file name in services/telephony/providers (generic, messagenet, voipvoice…)
#   trunk-name:        letters, digits, dashes (e.g. ufficio-messagenet)
#   inbound-extension: where incoming calls ring (default 1000)
set -euo pipefail
cd "$(dirname "$0")"

PROVIDERS_DIR=../../services/telephony/providers
provider=${1:-}; name=${2:-}; extension=${3:-1000}
if [ -z "$provider" ] || [ -z "$name" ]; then
  echo "Uso: $0 <provider> <nome-trunk> [interno]"
  echo "Provider disponibili: $(ls "$PROVIDERS_DIR" | sed 's/\.json$//' | tr '\n' ' ')"
  exit 1
fi
[[ "$name" =~ ^[a-z0-9-]+$ ]] || { echo "Nome trunk: solo minuscole, numeri e trattini"; exit 1; }
tpl="$PROVIDERS_DIR/$provider.json"
[ -f "$tpl" ] || { echo "Provider '$provider' non trovato"; exit 1; }

get() { jq -r ".$1 // empty" "$tpl"; }
has_field() { jq -e --arg f "$1" '.fields | index($f)' "$tpl" >/dev/null; }
xml() { sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g' -e 's/"/\&quot;/g'; }

echo "== Nuovo trunk $(get name) =="
[ "$(get verified)" = "true" ] || echo "Nota: $(get notes)"

registrar=$(get registrar)
if [ -z "$registrar" ] || has_field registrar; then
  read -rp "Server SIP (registrar)${registrar:+ [$registrar]}: " input
  registrar=${input:-$registrar}
fi
[ -n "$registrar" ] || { echo "Server obbligatorio"; exit 1; }
read -rp "Utente SIP: " username
auth_username=$username
if has_field auth_username; then
  read -rp "Utente di autenticazione [$username]: " input
  auth_username=${input:-$username}
fi
read -rsp "Password SIP: " password; echo
read -rp "Numero principale (es. 0612345678): " number
[ -n "$username" ] && [ -n "$password" ] && [ -n "$number" ] || { echo "Dati mancanti"; exit 1; }

port=$(get port); transport=$(get transport); proxy=$(get proxy)
expire=$(get expire_seconds); ping=$(get ping_seconds)

gw=conf/sip_profiles/external/$name.xml
umask 077
cat > "$gw" <<EOF
<include>
  <!-- Generated by add-trunk.sh from provider template '$provider' -->
  <gateway name="$name">
    <param name="realm" value="$(printf %s "$registrar" | xml):$port"/>
    <param name="proxy" value="$(printf %s "${proxy:-$registrar}" | xml):$port"/>
    <param name="register-transport" value="$transport"/>
    <param name="username" value="$(printf %s "$username" | xml)"/>
    <param name="auth-username" value="$(printf %s "$auth_username" | xml)"/>
    <param name="password" value="$(printf %s "$password" | xml)"/>
    <param name="from-user" value="$(printf %s "$username" | xml)"/>
    <param name="extension" value="$(printf %s "$number" | xml)"/>
    <param name="extension-in-contact" value="true"/>
    <param name="register" value="true"/>
    <param name="expire-seconds" value="$expire"/>
    <param name="retry-seconds" value="30"/>
    <param name="ping" value="$ping"/>
    <param name="caller-id-in-from" value="true"/>
    <param name="context" value="public"/>
  </gateway>
</include>
EOF

# Inbound: calls to the trunk number ring the chosen extension
cat > "conf/dialplan/public/50_$name.xml" <<EOF
<include>
  <extension name="inbound-$name">
    <condition field="destination_number" expression="^\+?(39)?$(printf %s "${number#+39}" | sed 's/[^0-9]//g')\$">
      <action application="set" data="domain_name=\$\${domain}"/>
      <action application="transfer" data="$extension XML default"/>
    </condition>
  </extension>
</include>
EOF

# Outbound: Italian national numbers and emergency only (no international = no toll fraud)
cat > "conf/dialplan/default/50_${name}_out.xml" <<EOF
<include>
  <extension name="outbound-$name">
    <condition field="destination_number" expression="^(11[2358]|0\d{5,10}|3\d{8,9})\$">
      <action application="set" data="effective_caller_id_number=$(printf %s "$number" | xml)"/>
      <action application="set" data="effective_caller_id_name=$(printf %s "$number" | xml)"/>
      <action application="bridge" data="sofia/gateway/$name/\$1"/>
    </condition>
  </extension>
</include>
EOF
umask 022
chmod 644 "conf/dialplan/public/50_$name.xml" "conf/dialplan/default/50_${name}_out.xml"

esl=$(grep '^ESL_PASSWORD=' .env | cut -d= -f2)
fs() { docker compose exec -T freeswitch fs_cli -p "$esl" -x "$1"; }
fs "reloadxml" >/dev/null
fs "sofia profile external rescan" >/dev/null
echo "Trunk '$name' creato, attendo la registrazione…"
sleep 5
fs "sofia status gateway $name" | grep -E '^(Name|Proxy|Username|State|Status|Uptime)' || true
